def is_redundant(candidate: str, existing_list: list[str]) -> bool:
    """Returns True if candidate is already present or too close to an existing translation."""
    cand_norm = re.sub(r"[\s\u200c،,/|().!؟?]+", " ", candidate).strip()
    for ex in existing_list:
        ex_norm = re.sub(r"[\s\u200c،,/|().!؟?]+", " ", ex).strip()
        if cand_norm == ex_norm:
            return True
        if cand_norm in ex_norm or ex_norm in cand_norm:
            # Check if candidate is a short word already contained in existing translation
            if len(cand_norm) < 12 or cand_norm == ex_norm:
                return True
    return False


def enrich_contents(concepts: list[dict], contents: list[dict], has_id: bool) -> tuple[list[dict], int, int]:
    """
    Appends new Persian translations to `contents` while preserving all existing items verbatim.
    Returns (new_contents_list, modified_concepts_count, added_translations_count).
    """
    import uuid
    by_cid: dict[str, list[dict]] = {}
    for c in contents:
        by_cid.setdefault(str(c["conceptId"]), []).append(c)

    sample_template = contents[0]

    new_contents = [copy.deepcopy(c) for c in contents]
    modified_concepts = 0
    added_translations = 0

    for concept in concepts:
        cid_str = str(concept["id"])
        cid_int = int(cid_str) if cid_str.isdigit() else -1
        c_items = by_cid.get(cid_str, [])
        es_items = [x for x in c_items if x["languageCode"] == "es"]
        fa_items = [x for x in c_items if x["languageCode"] == "fa"]
        if not es_items or not fa_items:
            continue

        es_text = es_items[0]["text"]
        es_key = norm_es(es_text)
        existing_fa = [x["text"] for x in fa_items]
        max_idx = max(int(x.get("translationIndex", 0)) for x in fa_items)

        candidates = []
        if cid_int in CONCEPT_ID_ENRICHMENTS:
            candidates.extend(CONCEPT_ID_ENRICHMENTS[cid_int])
        if es_key in LEXICAL_ENRICHMENTS:
            candidates.extend(LEXICAL_ENRICHMENTS[es_key])

        if not candidates:
            continue

        added_for_concept = 0
        for cand in candidates:
            if not is_redundant(cand, existing_fa):
                max_idx += 1
                existing_fa.append(cand)
                new_row = {}
                if has_id:
                    new_row["id"] = str(uuid.uuid5(uuid.NAMESPACE_OID, f"yadin-fa-{cid_str}-{max_idx}-{cand}"))
                new_row["conceptId"] = concept["id"]
                new_row["languageCode"] = "fa"
                new_row["text"] = cand
                new_row["phonetic"] = None
                if "audioPath" in sample_template:
                    new_row["audioPath"] = None
                    new_row["imagePath"] = None
                    new_row["exampleSentence"] = None
                    new_row["exampleTranslation"] = None
                new_row["notes"] = None
                new_row["translationIndex"] = max_idx
                new_contents.append(new_row)
                added_for_concept += 1
                added_translations += 1

        if added_for_concept > 0:
            modified_concepts += 1

    return new_contents, modified_concepts, added_translations


def verify_invariants(orig_concepts, new_concepts, orig_contents, new_contents, has_id: bool):
    """Strictly verifies all 9 user database rules."""
    assert orig_concepts == new_concepts, "INVARIANT VIOLATION: concepts list was modified!"
    assert len(new_contents) >= len(orig_contents), "INVARIANT VIOLATION: content rows were deleted!"
    # Every original content row must be preserved at the exact same position and with identical fields
    for i, orig_row in enumerate(orig_contents):
        assert new_contents[i] == orig_row, f"INVARIANT VIOLATION at content index {i}: {orig_row} != {new_contents[i]}"
    # Every newly appended row must be a valid 'fa' translation for an existing conceptId
    concept_ids = {c["id"] for c in orig_concepts}
    for extra_row in new_contents[len(orig_contents):]:
        assert extra_row["languageCode"] == "fa", "INVARIANT VIOLATION: non-fa row added!"
        assert extra_row["conceptId"] in concept_ids, "INVARIANT VIOLATION: unknown conceptId!"
        assert extra_row["translationIndex"] >= 1, "INVARIANT VIOLATION: translationIndex < 1!"
    if has_id:
        ids = [c["id"] for c in new_contents]
        assert len(ids) == len(set(ids)), "INVARIANT VIOLATION: duplicate content IDs!"


